import 'dart:async';
import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:flutter/material.dart';
import 'package:physical_therapy/models/patient_model.dart';
import 'package:physical_therapy/repositories/patient_repository.dart';

class PatientProvider extends ChangeNotifier {
  final PatientRepository _patientRepository = PatientRepository();

  List<PatientModel> _patients = [];
  bool _isLoading = false;
  String? _error;
  StreamSubscription<List<PatientModel>>? _patientsSubscription;

  List<PatientModel> get patients => List.unmodifiable(_patients);
  bool get isLoading => _isLoading;
  String? get error => _error;

  PatientProvider() {
    _listenToPatients();
  }

  void _listenToPatients() {
    _isLoading = true;
    notifyListeners();

    _patientsSubscription?.cancel();
    _patientsSubscription = _patientRepository.getPatientsStream().listen(
      (patientsList) {
        _patients = patientsList;
        _isLoading = false;
        _error = null;
        notifyListeners();
      },
      onError: (err) {
        _isLoading = false;
        _error = err.toString();
        notifyListeners();
      },
    );
  }

  Future<void> addPatient({
    required String name,
    required String phone,
    required String address,
    required String medicalNotes,
    double? latitude,
    double? longitude,
    bool commissionEnabled = false,
    double? commissionAmount,
    int commissionSessionsTarget = 3,
    int? planTotalSessions,
  }) async {
    _isLoading = true;
    notifyListeners();

    try {
      final newPatient = PatientModel(
        id: '', // Generated by Firestore
        name: name,
        phone: phone,
        address: address,
        medicalNotes: medicalNotes,
        location: (latitude != null && longitude != null)
            ? GeoPoint(latitude, longitude)
            : null,
        createdAt: DateTime.now(),
        commissionEnabled: commissionEnabled,
        commissionAmount: commissionEnabled ? commissionAmount : null,
        commissionSessionsCount: 0,
        commissionSessionsTarget: commissionSessionsTarget,
        planTotalSessions: planTotalSessions,
        planStartDate: planTotalSessions != null ? DateTime.now() : null,
      );

      await _patientRepository.addPatient(newPatient);
      _error = null;
    } catch (e) {
      _error = e.toString();
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  Future<void> updatePatient(
    PatientModel patient, {
    required String name,
    required String phone,
    required String address,
    required String medicalNotes,
    double? latitude,
    double? longitude,
    bool clearLocation = false,
    bool? commissionEnabled,
    double? commissionAmount,
    int? commissionSessionsTarget,
    int? planTotalSessions,
    bool resetPlanStartDate = false,
    bool clearPlan = false,
  }) async {
    _isLoading = true;
    notifyListeners();

    try {
      final isCommEnabled = commissionEnabled ?? patient.commissionEnabled;

      DateTime? newPlanStartDate = patient.planStartDate;
      if (clearPlan) {
        newPlanStartDate = null;
      } else if (resetPlanStartDate) {
        newPlanStartDate = DateTime.now();
      } else if (patient.planStartDate == null && planTotalSessions != null) {
        newPlanStartDate = DateTime.now();
      }

      final updatedPatient = patient.copyWith(
        name: name,
        phone: phone,
        address: address,
        medicalNotes: medicalNotes,
        location: (latitude != null && longitude != null)
            ? GeoPoint(latitude, longitude)
            : null,
        clearLocation: clearLocation,
        commissionEnabled: isCommEnabled,
        commissionAmount: isCommEnabled ? (commissionAmount ?? patient.commissionAmount) : null,
        clearCommissionAmount: !isCommEnabled,
        commissionSessionsCount: isCommEnabled ? patient.commissionSessionsCount : 0,
        commissionSessionsTarget: commissionSessionsTarget ?? patient.commissionSessionsTarget,
        planTotalSessions: clearPlan ? null : (planTotalSessions ?? patient.planTotalSessions),
        planStartDate: newPlanStartDate,
        clearPlan: clearPlan,
      );

      await _patientRepository.updatePatient(updatedPatient);
      _error = null;
    } catch (e) {
      _error = e.toString();
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  Future<void> deletePatient(String patientId) async {
    _isLoading = true;
    notifyListeners();

    try {
      await _patientRepository.deletePatient(patientId);
      _error = null;
    } catch (e) {
      _error = e.toString();
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  /// Completes the commission cycle for a patient.
  Future<void> completeCommissionCycle(PatientModel patient) async {
    if (patient.commissionAmount == null) return;
    _isLoading = true;
    notifyListeners();

    try {
      await _patientRepository.completeCommissionCycle(
        patient.id,
        patient.commissionAmount!,
        patient.name,
      );
      _error = null;
    } catch (e) {
      _error = e.toString();
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  /// Stream of all paid commissions across all patients.
  Stream<List<Map<String, dynamic>>> getPaidCommissionsStream() {
    return _patientRepository.getCommissionHistoryStream();
  }

  @override
  void dispose() {
    _patientsSubscription?.cancel();
    super.dispose();
  }
}
