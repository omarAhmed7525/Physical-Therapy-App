import 'package:physical_therapy/core/services/firebase_service.dart';
import 'package:physical_therapy/models/patient_model.dart';

class PatientRepository {
  final FirebaseService _firebaseService = FirebaseService.instance;

  /// Stream of all patients sorted by creation date descending
  Stream<List<PatientModel>> getPatientsStream() {
    return _firebaseService.patientsCollection
        .orderBy('createdAt', descending: true)
        .snapshots()
        .map((snapshot) {
      return snapshot.docs.map((doc) {
        return PatientModel.fromMap(doc.data(), doc.id);
      }).toList();
    });
  }

  /// Fetch all patients once (future)
  Future<List<PatientModel>> fetchPatients() async {
    final snapshot = await _firebaseService.patientsCollection
        .orderBy('createdAt', descending: true)
        .get();
    return snapshot.docs.map((doc) {
      return PatientModel.fromMap(doc.data(), doc.id);
    }).toList();
  }

  /// Add a new patient. The document ID is auto-generated by Firestore.
  Future<String> addPatient(PatientModel patient) async {
    final docRef = await _firebaseService.patientsCollection.add(patient.toMap());
    return docRef.id;
  }

  /// Update an existing patient.
  Future<void> updatePatient(PatientModel patient) async {
    await _firebaseService.patientDoc(patient.id).update(patient.toMap());
  }

  /// Delete a patient and all their associated subcollection sessions atomically using a WriteBatch.
  Future<void> deletePatient(String patientId) async {
    final batch = _firebaseService.batch;

    // 1. Query all documents in sessions subcollection
    final sessionsSnapshot = await _firebaseService.sessionsCollection(patientId).get();

    // 2. Add all session deletions to the batch
    for (final doc in sessionsSnapshot.docs) {
      batch.delete(doc.reference);
    }

    // 3. Add the patient document deletion to the batch
    batch.delete(_firebaseService.patientDoc(patientId));

    // 4. Commit the batch atomically
    await batch.commit();
  }

  /// Fetch a single patient by ID.
  Future<PatientModel?> getPatientById(String patientId) async {
    final doc = await _firebaseService.patientDoc(patientId).get();
    if (doc.exists && doc.data() != null) {
      return PatientModel.fromMap(doc.data()!, doc.id);
    }
    return null;
  }
}
